//! Writes the read model's `assets` and `markets` rows from a vex-core configuration file, for
//! Postgres or ClickHouse.
//!
//! The gateway's `ScalingCache` turns engine integers into decimals with the Postgres rows, and
//! ClickHouse's views with their copies, so they must equal the engine's own symbol
//! configuration. They are generated from the `symbols` section of the core's file, read and
//! validated by vex-config's own code, never written by hand:
//!
//! ```text
//! cargo run -p readmodel-seeds -- postgres <vex-core config file> > seeds.sql
//! cargo run -p readmodel-seeds -- clickhouse <vex-core config file> > seeds.clickhouse.sql
//! ```
//!
//! The output is idempotent: it writes every configured asset and market again, which replaces
//! the stored row, and keeps the others, whose stored orders, balances and history still need
//! their scales.

use common::CoreMarketSpecification;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;
use std::process::ExitCode;
use vex_config::SymbolSpecificationConfig;

/// The database the seed SQL is for.
#[derive(Clone, Copy)]
enum Engine {
    Postgres,
    ClickHouse,
}

fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    let engine = match args.next().as_deref() {
        Some("postgres") => Engine::Postgres,
        Some("clickhouse") => Engine::ClickHouse,
        _ => return usage(),
    };
    let (Some(path), None) = (args.next(), args.next()) else {
        return usage();
    };
    match generate(engine, Path::new(&path)) {
        Ok(sql) => {
            print!("{sql}");
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("readmodel-seeds: {error}");
            ExitCode::FAILURE
        }
    }
}

fn usage() -> ExitCode {
    eprintln!("usage: readmodel-seeds <postgres|clickhouse> <vex-core config file>");
    ExitCode::from(2)
}

/// The seed SQL for `engine` from the vex-core configuration file at `path`.
fn generate(engine: Engine, path: &Path) -> Result<String, String> {
    // The `symbols` section alone, deserialized as vex-config's loader does and checked by its
    // validation. The rest of the file does not bear on these rows, and a production file is
    // incomplete without the secrets the core takes from its environment (its gateway key), which
    // seeding must not need. The VEX__ environment overrides are not read either: the rows
    // depend on the file alone.
    let symbols: SymbolSpecificationConfig = config::Config::builder()
        .add_source(config::File::from(path))
        .build()
        .and_then(|config| config.get("symbols"))
        .map_err(|error| format!("{}: {error}", path.display()))?;
    symbols
        .validate()
        .map_err(|error| format!("{}: {error}", path.display()))?;
    let source = path.file_name().unwrap_or_default().to_string_lossy();
    Ok(match engine {
        Engine::Postgres => postgres_sql(&symbols, &source),
        Engine::ClickHouse => clickhouse_sql(&symbols, &source),
    })
}

/// The rows to seed, in id order.
#[derive(Debug)]
struct Rows<'a> {
    /// asset id -> native scale
    assets: BTreeMap<u16, u64>,
    markets: BTreeMap<u32, &'a CoreMarketSpecification>,
}

/// The assets and markets of `symbols`, every listed asset whether a market trades it or not.
fn rows(symbols: &SymbolSpecificationConfig) -> Rows<'_> {
    Rows {
        assets: symbols
            .assets
            .iter()
            .map(|(&asset, spec)| (asset, spec.native_scale))
            .collect(),
        markets: symbols
            .symbols
            .values()
            .map(|spec| (spec.market_id, spec))
            .collect(),
    }
}

/// Upserts of `assets` and `markets` from `symbols`, in id order. Every integer keeps its bits in
/// the signed column (`as i16`, `as i32`, `as i64`), as the gateway decodes it (`as u16`, ...).
fn postgres_sql(symbols: &SymbolSpecificationConfig, source: &str) -> String {
    let Rows { assets, markets } = rows(symbols);
    let mut sql = format!(
        "-- Generated by readmodel-seeds from vex-core's {source}. Do not edit: regenerate it.\nBEGIN;\n"
    );
    if !assets.is_empty() {
        sql.push_str("\nINSERT INTO assets (asset_id, native_scale) VALUES\n");
        let rows: Vec<_> = assets
            .iter()
            .map(|(&asset, &scale)| format!("    ({}, {})", asset as i16, scale as i64))
            .collect();
        sql.push_str(&rows.join(",\n"));
        sql.push_str(
            "\nON CONFLICT (asset_id) DO UPDATE SET native_scale = EXCLUDED.native_scale;\n",
        );
    }

    if !markets.is_empty() {
        sql.push_str(
            "\nINSERT INTO markets (market_id, base_asset, quote_asset, quote_scale_k) VALUES\n",
        );
        let rows: Vec<_> = markets
            .values()
            .map(|spec| {
                format!(
                    "    ({}, {}, {}, {})",
                    spec.market_id as i32,
                    spec.base_asset as i16,
                    spec.quote_asset as i16,
                    spec.quote_scale_k as i64
                )
            })
            .collect();
        sql.push_str(&rows.join(",\n"));
        sql.push_str(
            "\nON CONFLICT (market_id) DO UPDATE SET base_asset = EXCLUDED.base_asset, \
             quote_asset = EXCLUDED.quote_asset, quote_scale_k = EXCLUDED.quote_scale_k;\n",
        );
    }

    sql.push_str("\nCOMMIT;\n");
    sql
}

/// Inserts of `assets` and `markets` from `symbols`, in id order, each a statement that ends with
/// a semicolon. The tables are ReplacingMergeTrees, so a row written again replaces the stored
/// one.
fn clickhouse_sql(symbols: &SymbolSpecificationConfig, source: &str) -> String {
    let Rows { assets, markets } = rows(symbols);
    let mut sql = format!(
        "-- Generated by readmodel-seeds from vex-core's {source}. Do not edit: regenerate it.\n"
    );
    if !assets.is_empty() {
        let rows: Vec<_> = assets
            .iter()
            .map(|(asset, scale)| format!("    ({asset}, {scale})"))
            .collect();
        writeln!(
            sql,
            "INSERT INTO assets (asset_id, native_scale) VALUES\n{};",
            rows.join(",\n")
        )
        .expect("writing to a String cannot fail");
    }
    if !markets.is_empty() {
        let rows: Vec<_> = markets
            .values()
            .map(|spec| {
                format!(
                    "    ({}, {}, {}, {})",
                    spec.market_id, spec.base_asset, spec.quote_asset, spec.quote_scale_k
                )
            })
            .collect();
        writeln!(
            sql,
            "INSERT INTO markets (market_id, base_asset, quote_asset, quote_scale_k) VALUES\n{};",
            rows.join(",\n")
        )
        .expect("writing to a String cannot fail");
    }
    sql
}

#[cfg(test)]
mod tests {
    use super::*;
    use common::MarketType;
    use std::path::PathBuf;
    use vex_config::symbols::AssetSpec;
    use vex_config::{ConfigLoader, Environment};

    fn market(base_asset: u16, quote_asset: u16) -> CoreMarketSpecification {
        CoreMarketSpecification::builder()
            .market_id(((quote_asset as u32) << 16) | base_asset as u32)
            .market_type(MarketType::Spot)
            .quote_scale_k(10)
            .base_native_scale(100_000_000)
            .quote_native_scale(1_000_000)
            .build()
            .unwrap()
    }

    fn asset(native_scale: u64) -> AssetSpec {
        AssetSpec {
            native_scale,
            max_supply: 1,
        }
    }

    /// `markets` and their assets, at the markets' native scales.
    fn symbols(
        markets: impl IntoIterator<Item = CoreMarketSpecification>,
    ) -> SymbolSpecificationConfig {
        let mut symbols = SymbolSpecificationConfig::for_environment(&Environment::Production);
        for spec in markets {
            symbols
                .assets
                .insert(spec.base_asset, asset(spec.base_native_scale));
            symbols
                .assets
                .insert(spec.quote_asset, asset(spec.quote_native_scale));
            symbols.symbols.insert(spec.market_id, spec);
        }
        symbols
    }

    /// The vex-core checkout of the rev Cargo.lock pins, where cargo fetched vex-config from.
    fn pinned_core_checkout() -> PathBuf {
        let output = std::process::Command::new(env!("CARGO"))
            .args([
                "metadata",
                "--format-version=1",
                "--locked",
                "--manifest-path",
            ])
            .arg(Path::new(env!("CARGO_MANIFEST_DIR")).join("../../Cargo.toml"))
            .output()
            .expect("cargo metadata runs");
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let metadata: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
        let manifest = metadata["packages"]
            .as_array()
            .unwrap()
            .iter()
            .find(|package| package["name"] == "vex-config")
            .and_then(|package| package["manifest_path"].as_str())
            .expect("vex-config is a dependency");
        // <checkout>/vex-config/Cargo.toml
        Path::new(manifest)
            .ancestors()
            .nth(2)
            .unwrap()
            .to_path_buf()
    }

    #[test]
    fn committed_development_seeds_match_the_pinned_core() {
        let config = pinned_core_checkout().join("config.dev.yaml");
        for (engine, name, file, committed) in [
            (
                Engine::Postgres,
                "postgres",
                "development.sql",
                include_str!("../development.sql"),
            ),
            (
                Engine::ClickHouse,
                "clickhouse",
                "development.clickhouse.sql",
                include_str!("../development.clickhouse.sql"),
            ),
        ] {
            assert!(
                generate(engine, &config).unwrap() == committed,
                "readmodel/seeds/{file} differs from vex-core's {}; regenerate it with\n  \
                 cargo run -p readmodel-seeds -- {name} {} > readmodel/seeds/{file}",
                config.display(),
                config.display()
            );
        }
    }

    #[test]
    fn a_production_file_needs_only_its_symbols() {
        // vex-core's production file has no gateway authentication key: the core takes it from
        // VEX__CORE_NETWORKING__GATEWAY_AUTHENTICATION_KEY, so its loader refuses the file on
        // its own.
        let development = pinned_core_checkout().join("config.dev.yaml");
        let file = std::fs::read_to_string(&development).unwrap();
        let file = file
            .replace("environment: development", "environment: production")
            .replace(
                "enable_authentication: false",
                "enable_authentication: true",
            );
        let dir = tempfile::tempdir().unwrap();
        let production = dir.path().join("config.prod.yaml");
        std::fs::write(&production, file).unwrap();
        assert!(
            ConfigLoader::new()
                .without_env_prefix()
                .load_from_file(&production)
                .is_err()
        );

        for engine in [Engine::Postgres, Engine::ClickHouse] {
            assert_eq!(
                generate(engine, &production).unwrap(),
                generate(engine, &development)
                    .unwrap()
                    .replace("config.dev.yaml", "config.prod.yaml")
            );
        }
    }

    #[test]
    fn invalid_symbols_are_refused() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("config.yaml");
        // Market 65538 is quote asset 1 << 16 | base asset 2, not base asset 3.
        let file = r#"
symbols:
  assets:
    "1":
      native_scale: 1000000
      max_supply: 1
    "3":
      native_scale: 100000000
      max_supply: 1
  symbols:
    "65538":
      market_id: 65538
      market_type: Spot
      base_asset: 3
      quote_asset: 1
      quote_scale_k: 1
      base_native_scale: 100000000
      quote_native_scale: 1000000
      taker_fee: 0
      maker_fee: 0
      slippage: 150
"#;
        std::fs::write(&path, file).unwrap();

        let error = generate(Engine::ClickHouse, &path).unwrap_err();

        assert!(
            error.contains("Symbol ID 65538 does not match quote_asset << 16 | base_asset = 65539"),
            "{error}"
        );
    }

    #[test]
    fn integers_keep_their_bits_in_signed_columns() {
        let mut spec = market(40_000, 50_000);
        spec.base_native_scale = 10_000_000_000_000_000_000;
        spec.quote_scale_k = u64::MAX;
        let sql = postgres_sql(&symbols([spec]), "test");

        // asset 40000 = -25536 as i16, 10^19 = -8446744073709551616 as i64
        assert!(sql.contains("    (-25536, -8446744073709551616)"), "{sql}");
        // market 50000 << 16 | 40000 = -1018127296 as i32, u64::MAX = -1 as i64
        assert!(
            sql.contains("    (-1018127296, -25536, -15536, -1)"),
            "{sql}"
        );
    }

    #[test]
    fn clickhouse_columns_are_unsigned() {
        let mut spec = market(40_000, 50_000);
        spec.base_native_scale = 10_000_000_000_000_000_000;
        spec.quote_scale_k = u64::MAX;

        let sql = clickhouse_sql(&symbols([spec]), "test");

        assert_eq!(
            sql,
            "-- Generated by readmodel-seeds from vex-core's test. Do not edit: regenerate it.\n\
             INSERT INTO assets (asset_id, native_scale) VALUES\n    \
             (40000, 10000000000000000000),\n    (50000, 1000000);\n\
             INSERT INTO markets (market_id, base_asset, quote_asset, quote_scale_k) VALUES\n    \
             (3276840000, 40000, 50000, 18446744073709551615);\n"
        );
    }

    #[test]
    fn an_asset_without_a_market_is_seeded() {
        let mut symbols = symbols([]);
        symbols.assets.insert(4, asset(100));

        assert_eq!(
            clickhouse_sql(&symbols, "test"),
            "-- Generated by readmodel-seeds from vex-core's test. Do not edit: regenerate it.\n\
             INSERT INTO assets (asset_id, native_scale) VALUES\n    (4, 100);\n"
        );
    }

    /// A market or asset that leaves the configuration keeps its row: its stored orders and
    /// balances still need its scale.
    #[test]
    fn an_empty_configuration_writes_nothing_to_postgres() {
        let sql = postgres_sql(&symbols([]), "test");

        assert_eq!(
            sql,
            "-- Generated by readmodel-seeds from vex-core's test. Do not edit: regenerate it.\n\
             BEGIN;\n\nCOMMIT;\n"
        );
    }

    #[test]
    fn an_empty_configuration_writes_nothing_to_clickhouse() {
        let sql = clickhouse_sql(&symbols([]), "test");

        assert_eq!(
            sql,
            "-- Generated by readmodel-seeds from vex-core's test. Do not edit: regenerate it.\n"
        );
    }
}
